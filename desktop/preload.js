const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('huroh', {
    desktop: true,
    vidro: process.argv.includes('--huroh-vidro'),
    idiomaInstalacao: (process.argv.find(arg => arg.startsWith('--huroh-idioma=')) || '').split('=')[1] || null,

    abrir: (pagina, acao) => ipcRenderer.send('abrir', pagina, acao),
    ratoAtivo: ativo => ipcRenderer.send('rato-ativo', ativo),
    paginaAtual: pagina => ipcRenderer.send('pagina-atual', pagina),
    esconderLateral: () => ipcRenderer.send('mostrar-lateral', false),
    mostrarLateral: visivel => ipcRenderer.send('mostrar-lateral', visivel),
    estadoLateral: () => ipcRenderer.invoke('estado-lateral'),
    sair: () => ipcRenderer.send('sair'),
    appPronta: () => ipcRenderer.send('app-pronta'),
    arranque: ligado => ipcRenderer.invoke('arranque', ligado),
    arranqueDisponivel: () => ipcRenderer.invoke('arranque-disponivel'),
    janela: acao => ipcRenderer.send('janela', acao),
    janelaPronta: () => ipcRenderer.send('janela-pronta'),
    atualizacao: () => ipcRenderer.invoke('atualizacao-estado'),
    atualizacaoAuto: ligado => ipcRenderer.send('atualizacao-auto', ligado),
    procurarAtualizacao: () => ipcRenderer.send('atualizacao-procurar'),
    instalarAtualizacao: () => ipcRenderer.send('atualizacao-instalar'),
    aoAtualizacao: funcao => ipcRenderer.on('atualizacao', (_evento, estado) => funcao(estado)),
    guardarBackup: (dia, conteudo) => ipcRenderer.invoke('guardar-backup', dia, conteudo),
    apagarBackups: () => ipcRenderer.invoke('apagar-backups'),
    prepararGoogle: () => ipcRenderer.invoke('google-preparar'),
    abrirGoogle: url => ipcRenderer.send('google-abrir', url),
    alturaLogin: altura => ipcRenderer.send('altura-login', altura),
    aoEntrarGoogle: funcao => ipcRenderer.on('google-resultado', (_evento, sessao) => funcao(sessao)),

    aoNavegar: funcao => ipcRenderer.on('navegar', (_evento, pagina) => funcao(pagina)),
    aoAcao: funcao => ipcRenderer.on('acao', (_evento, acao) => funcao(acao)),
    aoMudarPagina: funcao => ipcRenderer.on('pagina-atual', (_evento, pagina) => funcao(pagina)),
    aoRato: funcao => ipcRenderer.on('rato', (_evento, ponto) => funcao(ponto)),
    aoApresentar: funcao => ipcRenderer.on('apresentar', (_evento, origem) => funcao(origem)),
    aoEsconderJanela: funcao => ipcRenderer.on('janela-escondida', () => funcao()),
    aoMostrarJanela: funcao => ipcRenderer.on('janela-mostrada', () => funcao()),
    aoMudarLateral: funcao => ipcRenderer.on('lateral-mudou', (_evento, visivel) => funcao(visivel)),
});
